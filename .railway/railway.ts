// ArkLaw's Railway settings (Infrastructure as Code), replacing railway.json.
//
// Why: Railway stops reading railway.json (its "Config as Code") on 1 Dec 2026
// (the CLI's date; the docs say 1 Jan 2027). After that, a build would use the
// service's own stored settings, which have the default builder, no Dockerfile
// path and no health check. Railway always builds a root `Dockerfile` when it
// finds one, and the root Dockerfile here is the upstream hosted product, NOT
// ArkLaw. So without this file the next build after the cutoff would ship the
// wrong app.
//
// Railway does NOT read this file on deploy. It changes nothing until someone
// runs, from the repo root, with the CLI linked to Arklaw / production /
// ms-word-addin:
//   npm ci --prefix .railway --ignore-scripts
//   railway config plan  --environment production   (preview; read it)
//   railway config apply --environment production   (stores the settings AND redeploys)
// Only with Stuart's OK: the apply is a deploy.
//
// Partial: this file manages ONLY the ms-word-addin service. Without the
// partial line an apply would treat anything not listed as something to delete.
// Variables are unmanaged: this file never reads, adds or deletes a variable.
//
// The values below are exactly railway.json's (generated by
// `railway config migrate --service ms-word-addin --variables=unmanaged`, then
// the two settings the generator left as comments were written in by hand).
// .railway/settings.test.mjs checks they stay that way.
import { defineRailway, github, project, service } from "railway/iac";

export const partial = "ms-word-addin";

export default defineRailway(() => {
  const msWordAddin = service("ms-word-addin", {
    source: github("arkaloncrm/ms-word-addin", { branch: "main", checkSuites: false }),
    // The ArkLaw community build (bring-your-own-key). Never the root Dockerfile.
    // No builder line: Railway always builds with a Dockerfile when it finds one,
    // and on 01/11/2026 ArcDental saw that Railway does not store builder
    // DOCKERFILE (it stayed in every plan and every apply redeployed for nothing).
    // After the first apply, check Railway shows this path; if it does not, set the
    // service variable RAILWAY_DOCKERFILE_PATH=Dockerfile.community instead.
    build: { dockerfilePath: "Dockerfile.community" },
    healthcheck: "/health",
    healthcheckTimeout: 60,
    // Restart on failure is Railway's default policy, so only the retry limit is
    // written (the same as ArcDental's file; Railway does not store the default).
    deploy: { restartPolicyMaxRetries: 5 },
    replicas: { "sfo": 1 },
  });

  return project("Arklaw", {
    variables: { managed: false },
    resources: [msWordAddin],
  });
});
